import tensorflow as tf

texts = [
    "Patient John has fever",
    "Patient Alice has diabetes",
    "Patient David has cough"
]

# Replace Patient Names
anonymous = [
    text.replace("John","Person") \
        .replace("Alice","Person") \
        .replace("David","Person")
    for text in texts
]

print("Anonymous Text\n")

for text in anonymous:
    print(text)

# Convert Text to Sequence
tokenizer = tf.keras.preprocessing.text.Tokenizer()

tokenizer.fit_on_texts(anonymous)

sequence = tokenizer.texts_to_sequences(anonymous)

print("\nText Sequences")

for s in sequence:
    print(s)

